import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { join, resolve } from 'node:path';

const execFileAsync = promisify(execFile);
const root = resolve(import.meta.dirname, '..');
const desktop = resolve(root, 'apps/desktop');
const manifest = JSON.parse(await readFile(join(desktop, 'package.json'), 'utf8'));
const version = manifest.version;
const source = join(desktop, 'out', 'QoderWake-win32-x64');
if (!existsSync(join(source, 'QoderWake.exe')))
  throw new Error('Run the desktop package step before building the installer.');
const output = join(desktop, 'out', 'make', 'inno');
await mkdir(output, { recursive: true });
const script = join(output, 'QoderWake.iss');
const escapedSource = source.replaceAll('\\', '/');
const escapedOutput = output.replaceAll('\\', '/');
const iss = `; Generated by scripts/make-windows-inno.mjs. Do not edit by hand.
#define MyAppName "QoderWake"
#define MyAppVersion "${version}"
#define MyAppPublisher "QoderWake"
#define MyAppURL "https://github.com/bujidaoei/workdude"
#define MyAppExeName "QoderWake.exe"
[Setup]
AppId={{5E9F36A2-7D55-4B89-9F5E-7E3D0A4D21C8}
AppName={#MyAppName}
AppVersion={#MyAppVersion}
AppPublisher={#MyAppPublisher}
AppPublisherURL={#MyAppURL}
; Keep this project's installer separate from the official QoderWake installer.
; The distinct AppId prevents Inno from replacing the official uninstall registration.
DefaultDirName={localappdata}\\Programs\\QoderWake Desktop
DisableDirPage=no
DefaultGroupName={#MyAppName}
DisableProgramGroupPage=no
PrivilegesRequired=lowest
ArchitecturesInstallIn64BitMode=x64
OutputDir=${escapedOutput}
OutputBaseFilename=QoderWake-${version}-Windows-x64-Setup
; Fast single-block compression. The published installer is this Inno package,
; so the release path does not spend another full pass on Squirrel or ZIP.
Compression=lzma2/fast
SolidCompression=no
WizardStyle=modern
UninstallDisplayName=QoderWake {#MyAppVersion}
Uninstallable=yes
[Files]
Source: "${escapedSource}\\*"; DestDir: "{app}"; Flags: recursesubdirs createallsubdirs ignoreversion
[Icons]
Name: "{group}\\QoderWake"; Filename: "{app}\\{#MyAppExeName}"
Name: "{autodesktop}\\QoderWake"; Filename: "{app}\\{#MyAppExeName}"; Tasks: desktopicon
[Tasks]
Name: "desktopicon"; Description: "创建桌面快捷方式"; GroupDescription: "附加快捷方式："
[Run]
Filename: "{app}\\{#MyAppExeName}"; Description: "启动 QoderWake"; Flags: nowait postinstall skipifsilent
[UninstallDelete]
Type: filesandordirs; Name: "{app}"
`;
await writeFile(script, iss, 'utf8');
const candidates = [
  process.env.INNO_SETUP_COMPILER,
  join(process.env.LOCALAPPDATA ?? '', 'Programs', 'Inno Setup 6', 'ISCC.exe'),
  'C:\\\\Program Files (x86)\\\\Inno Setup 6\\\\ISCC.exe',
  'C:\\\\Program Files\\\\Inno Setup 6\\\\ISCC.exe',
].filter(Boolean);
const compiler = candidates.find((candidate) => existsSync(candidate));
if (!compiler) throw new Error('Inno Setup compiler (ISCC.exe) was not found.');
await execFileAsync(compiler, ['/Q', script], { windowsHide: true });
console.log(join(output, `QoderWake-${version}-Windows-x64-Setup.exe`));
